import { chromium } from "@playwright/test";
const [,, path, out, actions = ""] = process.argv;
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: process.env.SCHEME || "light" });
const page = await ctx.newPage();
const errors = [];
page.on("console", (m) => m.type() === "error" && errors.push(m.text().slice(0, 200)));
page.on("pageerror", (e) => errors.push(String(e).slice(0, 200)));
await page.goto("http://localhost:3001/login");
await page.fill("#username", "admin");
await page.fill("#password", "netfly-dev-admin");
await page.keyboard.press("Enter");
await page.waitForURL("http://localhost:3001/", { timeout: 15000 });
await page.goto("http://localhost:3001" + path, { waitUntil: "networkidle" });
if (actions) await new Function("page", `return (async () => { ${actions} })()`)(page);
await page.waitForTimeout(800);
await page.screenshot({ path: out });
console.log("URL", page.url(), "ERRORS", JSON.stringify(errors));
await browser.close();
